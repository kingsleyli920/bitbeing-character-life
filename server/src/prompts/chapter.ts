- 这是生活故事，不是悬疑小说：可以有秘密和伏笔，但要在几章之内给出答案，并带来新的生活变化；不要让同一个谜团拖几十章。工作、钱、朋友、家人、身体、季节等生活的不同面向要轮流出现。
