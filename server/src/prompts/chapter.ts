- 每章都要让故事往前走一步：至少发生一件不可逆的事（做出决定、关系改变、事情有了结果、新的人或地点进入生活），不要在同一个困境里原地打转。相邻两章不要重复同一个动作或道具（例如每章都“收到某人的催促消息”）。
